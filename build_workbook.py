def funnel_base_formula(lead_type, includes=None, include_or=None, pairs=None, exclude_snoozed=True):
    # SUMPRODUCT (not COUNTIFS) so an OR-within-one-column condition (e.g.
    # subStage is EITHER "Correction Required" OR "Correction Applied") can be
    # expressed as a single summed term — COUNTIFS can only AND criteria.
    # NOTE: deliberately NOT filtering on M ("entered pipeline since launch")
    # here — this funnel covers the FULL book (matches Total Cases in Flow),
    # split only by Old/New Lead (created before/after 24 Aug), not restricted
    # to cases that entered the pipeline since launch. Removed 15 Sep 2026
    # per explicit instruction: showing only the since-launch subset next to
    # the "Total Cases in Flow" headline was confusing, not clarifying.
    terms = [f'({rng("AK")}="{lead_type}")']
    for col, val in (includes or []):
        terms.append(f'({rng(col)}="{val}")')
    if include_or:
        col, vals = include_or
        or_term = "+".join([f'({rng(col)}="{v}")' for v in vals])
        terms.append(f"({or_term})")
    if pairs:
        # OR across whole (stage, substage) pairs, e.g. (Applied,Awaiting) OR
        # (Filing,EC Applied) — needed when the OR spans two different columns
        # at once, which include_or (single-column OR) can't express. Pairs
        # are mutually exclusive by construction (a case has one stage/substage),
        # so summing the AND'd terms is a safe OR with no double-counting.
        or_terms = []
        for conds in pairs:
            and_str = "*".join([f'({rng(c)}="{v}")' for c, v in conds])
            or_terms.append(f"({and_str})")
        terms.append("(" + "+".join(or_terms) + ")")
    if exclude_snoozed:
        # Snoozed (queueBucket="snoozed") overrides every other tier — a
        # paused/RNR case in Doc, Filing, or Applied/Correction Required all
        # land in "Snoozed" instead of their stage-based tier, per explicit
        # instruction: "if a case has queueBucket=snoozed, put it under
        # snoozed category only."
        terms.append(f'({rng("F")}<>"snoozed")')
    return "=SUMPRODUCT(" + "*".join(terms) + ")"

