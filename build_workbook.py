# ---------------- Pause reasons (compact) ----------------
# Categorized from the REAL free-text note content (pausedReasonDetail) and
# dependency metadata (pauseDependencyServiceId, pauseDueToDependency), not
# the vague dropdown value (currentPauseReason — often just "Other" or blank,
# which is why the old version of this table was wrong: it made a large chunk
# of paused cases look undocumented when the real notes explain nearly all of
# them). Regex categorization isn't expressible as a live Excel formula, so
# these are computed here in Python and written as static values — same
# taxonomy already validated against the Paused cases tab earlier this session.
import re as _re

def categorize_pause_reason(row):
    text = str(row.get("pausedReasonDetail", "") or "").lower()
    if str(row.get("pauseDueToDependency", "")) == "Yes" or row.get("pauseDependencyServiceId"):
        return "Dependency on another case/service"
    if not text:
        return "Genuinely undocumented"
    if _re.search(r"otp|not (giving|share|cooperat)", text):
        return "Customer non-cooperation (OTP/verification refusal)"
    if _re.search(r"unavailable|not (picking|answering|responding|there)|disconnect|out of (country|town|station)|wife is not there|will come back|hold (the )?correction|hold for", text):
        return "Customer unavailable / requested hold"
    if "refund" in text:
        return "Refund case (should likely be closed, not paused)"
    if _re.search(r"not willing to accept|proceed with closing", text):
        return "Dispute — flagged for closure"
    if _re.search(r"portal.*(already|glitch|showing|not working|not visible)|glitch", text):
        return "BBMP portal issue or glitch"
    if _re.search(r"grievance|complaint", text):
        return "Grievance/complaint raised"
    if _re.search(r"family tree|document.*(not received|missing)|docs? not", text):
        return "Missing documents from customer"
    if _re.search(r"forest department|legal team|objection", text):
        return "Government/legal objection"
    if _re.search(r"bescom bill|bill.*already used|wrong (bescom )?bill|incorrect bill", text):
        return "Document/data conflict (e.g. bill reused/incorrect)"
    if _re.search(r"society|site visit|resident|builders name", text):
        return "Site/society/builder-level issue"
    if _re.search(r"deadline|missed|unable to arrange", text):
        return "Missed external deadline"
    return "Other (documented, uncategorized)"

