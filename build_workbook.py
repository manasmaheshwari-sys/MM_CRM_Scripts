def style_header(ws, row=1, ncols=None):
    ncols = ncols or ws.max_column
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.font = Font(name=FONT, bold=True, color=white, size=10)
        cell.fill = PatternFill("solid", fgColor=teal)
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        cell.border = Border(bottom=Side(style="thin", color=navy))

def autosize(ws, widths=None):
    for i, col in enumerate(ws.columns, start=1):
        letter = get_column_letter(i)
        if widths and letter in widths:
            ws.column_dimensions[letter].width = widths[letter]
            continue
        maxlen = 0
        for cell in col:
            if cell.value is not None:
                maxlen = max(maxlen, len(str(cell.value)))
        ws.column_dimensions[letter].width = min(max(maxlen + 2, 9), 32)

